# Strips AI-generated meta preambles like "This article discusses..." from summaries
SNIPPET_BOILERPLATE_RE = re.compile(
    r'^\s*(?:this|the)\s+(?:article|piece|post|report|guide|text|video|summary)\s+'
    r'(?:discusses|presents|introduces|explores|outlines|describes|covers|examines|explains|highlights|details|provides|offers)'
    r'\b[^.]*\.\s*',
    re.IGNORECASE
)

FRONTMATTER_RE = re.compile(r"^---\n(.*?)\n---\n(.*)$", re.DOTALL)


def _parse_frontmatter(content):
    """Returns (meta, body) or (None, None) if content isn't in the new YAML-frontmatter
    format. Kept as a lightweight inline parser (mirrors homelab-intake/intake/frontmatter.py)
    rather than a cross-repo import, since the dashboard already reads homelab-intake's files
    directly by path."""
    m = FRONTMATTER_RE.match(content)
    if not m:
        return None, None
    try:
        meta = yaml.safe_load(m.group(1)) or {}
    except yaml.YAMLError:
        return None, None
    return meta, m.group(2)


def _full_summary_from_body(body, heading_pattern):
    summary_match = re.search(heading_pattern, body, re.DOTALL)
    if not summary_match:
        return ''
    summary_text = SNIPPET_BOILERPLATE_RE.sub('', summary_match.group(1).strip()).strip()
    return re.sub(r'^(?:#{1,6}[^\n]*\n+)+', '', summary_text).strip()


def _snippet_from_body(body, heading_pattern):
    summary_text = _full_summary_from_body(body, heading_pattern)
    return summary_text[:150] + ('...' if len(summary_text) > 150 else '')


def _reading_minutes(body: str) -> int:
    return max(1, round(len(body.split()) / 250))


def _article_from_frontmatter(filename, content, meta, body):
    tags = meta.get('tags') or []
    content_type = meta.get('content_type') or ''
    return {
        'id': filename,
        'title': meta.get('title') or filename.replace('.md', ''),
        'date': (meta.get('date_processed') or '')[:19].replace('T', ' '),
        'source': meta.get('source_url') or '',
        'snippet': _snippet_from_body(body, r'## Summary\n\n(.*?)(?:\n##(?!#)|$)'),
        'is_duplicate': bool(meta.get('dup_of')),
        'auto_generated': bool(meta.get('auto_generated')),
        'tags': [str(t) for t in tags],
        # Proposed by the pipeline but not yet in the vocabulary -- surfaced for one-click
        # approval rather than applied automatically (homelab-intake docs/DESIGN.md §5/§6).
        'suggested_tags': [str(t) for t in (meta.get('suggested_tags') or [])],
        'raw_content': content.lower(),
        'content_type': content_type,
        # The "save this to learn from later" axis (homelab-intake docs/DESIGN.md §5).
        # Absent on articles processed before the field shipped -- those read as False
        # until scripts/backfill_educational.py has run over the corpus.
        'educational': bool(meta.get('educational')),
        'priority_score': meta.get('priority_score'),
        'why_it_matters': meta.get('why_it_matters'),
        'user_folders': [str(f) for f in (meta.get('user_folders') or [])],
        'reading_minutes': _reading_minutes(body),
    }


def _article_from_legacy(filename, content):
    title_match = re.search(r'^#\s+(.*)', content, re.MULTILINE)
    source_match = re.search(r'\*\*Source:\*\*\s+(.*)', content)
    date_match = re.search(r'\*\*Date:\*\*\s+(.*)', content)
    dup_match = re.search(r'\*\*Duplicate:\*\*\s+(True|False)', content)
    auto_match = re.search(r'\*\*AutoGenerated:\*\*\s+(True|False)', content)
    tags_match = re.search(r'\*\*Tags:\*\*\s+(.*)', content)

    return {
        'id': filename,
        'title': title_match.group(1) if title_match else filename.replace('.md', ''),
        'date': date_match.group(1) if date_match else '',
        'source': source_match.group(1) if source_match else '',
        'snippet': _snippet_from_body(content, r'## Local AI Summary[^\n]*\n(.*?)(?:\n##(?!#)|$)'),
        'is_duplicate': dup_match.group(1) == 'True' if dup_match else False,
        'auto_generated': auto_match.group(1) == 'True' if auto_match else False,
        'tags': [t.strip() for t in tags_match.group(1).split(',') if t.strip()] if tags_match else [],
        'suggested_tags': [],
        'raw_content': content.lower(),
        'content_type': '',
        'educational': False,  # legacy articles predate the field entirely
        'priority_score': None,
        'why_it_matters': None,
        'user_folders': [],
        'reading_minutes': _reading_minutes(content),
    }


_articles_cache: dict = {'signature': None, 'articles': None}


def _articles_dir_signature() -> tuple:
    """Cheap (file, mtime) fingerprint of the articles directory -- a stat-only pass over
    ~85 files costs ~1ms vs. ~1.3s to actually parse them all, so list_articles() (called
    on every page load, by every tab's initial-load timer, and it only gets slower as the
    archive grows) can skip the full re-parse whenever nothing has actually changed."""
    files = glob.glob(os.path.join(ARTICLES_DIR, '*.md'))
    return tuple(sorted((f, os.path.getmtime(f)) for f in files))


# No `status`: homelab-intake retired it on 2026-09-11. Reading state (read/favorite/
