def mark_duplicate(filename: str) -> bool:
    filepath = os.path.join(ARTICLES_DIR, filename)
    if not os.path.exists(filepath):
        return False
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()

    meta, body = _parse_frontmatter(content)
    if meta is not None:
        meta['dup_of'] = None if meta.get('dup_of') else 'manually flagged'
        yaml_block = yaml.safe_dump(meta, sort_keys=False, allow_unicode=True)
        with open(filepath, 'w', encoding='utf-8') as f:
            f.write(f"---\n{yaml_block}---\n{body}")
        _sync_index_row(filepath)
        return True

    if '**Duplicate:**' in content:
        content = re.sub(r'\*\*Duplicate:\*\*\s+(True|False)', '**Duplicate:** True', content)
    else:
        content = content.replace('\n## Local AI Summary', '\n**Duplicate:** True\n\n## Local AI Summary', 1)
    with open(filepath, 'w', encoding='utf-8') as f:
        f.write(content)
    return True


def _mutate_user_folders(filename: str, mutate) -> bool:
    """Shared round-trip for add_to_folder/remove_from_folder: parse -> mutate meta's
    user_folders list -> yaml.safe_dump -> rewrite. Same pattern as mark_duplicate(). A
    no-op (returns False) for legacy-format articles -- custom folders are new
    functionality with no need to also patch the old bold-header format."""
    filepath = os.path.join(ARTICLES_DIR, filename)
    if not os.path.exists(filepath):
        return False
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()

    meta, body = _parse_frontmatter(content)
    if meta is None:
        return False

    folders = [str(f) for f in (meta.get('user_folders') or [])]
    meta['user_folders'] = mutate(folders)
    yaml_block = yaml.safe_dump(meta, sort_keys=False, allow_unicode=True)
    with open(filepath, 'w', encoding='utf-8') as f:
        f.write(f"---\n{yaml_block}---\n{body}")
    _sync_index_row(filepath)
    return True


TAGS_VOCAB_FILE = os.path.expanduser('~/projects/homelab-intake/tags_vocabulary.json')


def _normalise_tag(tag: str) -> str:
    """Must stay identical to homelab-intake's intake/tags.py normalise() -- both sides
    decide 'is this the same tag' and a divergence would re-fork OpenSource/open-source."""
    return re.sub(r'[\s\-_/.]+', '', tag.strip().lower())


def load_tag_vocabulary() -> list[str]:
    """The controlled vocabulary the pipeline reuses, in FILE ORDER -- which is descending
    corpus frequency (homelab-intake/scripts/seed_tag_vocabulary.py writes it that way, and
    the tagging prompt injects the top N by taking the first N). Callers wanting alphabetical
    display should sort their own copy rather than changing this."""
    if not os.path.exists(TAGS_VOCAB_FILE):
        return []
    try:
        with open(TAGS_VOCAB_FILE, 'r', encoding='utf-8') as f:
            return list(json.load(f))
    except (OSError, ValueError):
        return []


def promote_tag(tag: str) -> str:
    """Add a tag to the live vocabulary so the pipeline starts auto-applying it. Returns the
    spelling actually stored -- an existing normalised match wins over the passed spelling,
    which is what stops 'open source' re-entering next to 'OpenSource'."""
    tag = tag.strip()
    vocab = load_tag_vocabulary()
    existing = {_normalise_tag(t): t for t in vocab}
    key = _normalise_tag(tag)
    if key in existing:
        return existing[key]
    # Appended, and written back in order -- NOT re-sorted. The file's order is the frequency
    # ranking the tagging prompt reads, so sorting here would silently destroy it on the first
    # tag you accept in the UI. Appending is also correct on the merits: a tag being promoted
    # for the first time is the least-used one in the vocabulary.
    vocab.append(tag)
    tmp_fd, tmp_path = tempfile.mkstemp(dir=os.path.dirname(TAGS_VOCAB_FILE), suffix='.tmp')
    try:
        with os.fdopen(tmp_fd, 'w', encoding='utf-8') as f:
            json.dump(vocab, f, indent=2, ensure_ascii=False)
        os.replace(tmp_path, TAGS_VOCAB_FILE)
    except BaseException:
        with contextlib.suppress(OSError):
            os.unlink(tmp_path)
        raise
    return tag


def _mutate_tags(filename: str, mutate) -> bool:
    """Same round-trip as _mutate_user_folders, over the `tags` list. Also drops the tag from
    `suggested_tags` whenever it lands in `tags`, so an accepted suggestion stops being
    offered."""
    filepath = os.path.join(ARTICLES_DIR, filename)
    if not os.path.exists(filepath):
        return False
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()

    meta, body = _parse_frontmatter(content)
    if meta is None:
        return False

    meta['tags'] = mutate([str(t) for t in (meta.get('tags') or [])])
    applied = {_normalise_tag(t) for t in meta['tags']}
    meta['suggested_tags'] = [
        str(t) for t in (meta.get('suggested_tags') or [])
        if _normalise_tag(str(t)) not in applied
    ]
    yaml_block = yaml.safe_dump(meta, sort_keys=False, allow_unicode=True)
    with open(filepath, 'w', encoding='utf-8') as f:
        f.write(f"---\n{yaml_block}---\n{body}")
    _sync_index_row(filepath)
    return True


def add_tag(filename: str, tag: str) -> bool:
    """No cap on manual additions -- the 3-6 limit constrains the model, which is the source
    of vocabulary sprawl, not the human curating it."""
    tag = tag.strip()
    if not tag:
        return False
    key = _normalise_tag(tag)
    return _mutate_tags(
        filename,
        lambda tags: tags if any(_normalise_tag(t) == key for t in tags) else tags + [tag],
    )


def remove_tag(filename: str, tag: str) -> bool:
    key = _normalise_tag(tag)
    return _mutate_tags(filename, lambda tags: [t for t in tags if _normalise_tag(t) != key])


def dismiss_suggested_tag(filename: str, tag: str) -> bool:
    """Reject a suggestion without applying it."""
    filepath = os.path.join(ARTICLES_DIR, filename)
    if not os.path.exists(filepath):
        return False
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()
    meta, body = _parse_frontmatter(content)
    if meta is None:
        return False
    key = _normalise_tag(tag)
    meta['suggested_tags'] = [
        str(t) for t in (meta.get('suggested_tags') or []) if _normalise_tag(str(t)) != key
    ]
    yaml_block = yaml.safe_dump(meta, sort_keys=False, allow_unicode=True)
    with open(filepath, 'w', encoding='utf-8') as f:
        f.write(f"---\n{yaml_block}---\n{body}")
    _sync_index_row(filepath)
    return True


def add_to_folder(filename: str, folder: str) -> bool:
    return _mutate_user_folders(filename, lambda folders: folders if folder in folders else folders + [folder])


def remove_from_folder(filename: str, folder: str) -> bool:
    return _mutate_user_folders(filename, lambda folders: [f for f in folders if f != folder])


def resubmit_article(filename: str) -> dict:
    filepath = os.path.join(ARTICLES_DIR, filename)
    if not os.path.exists(filepath):
        return {'error': 'Not found'}

    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()

    meta, _ = _parse_frontmatter(content)
    if meta is not None:
        url = meta.get('source_url')
        auto_generated = bool(meta.get('auto_generated'))
        if not url:
            return {'error': 'No source URL found in article'}
    else:
        source_match = re.search(r'\*\*Source:\*\*\s+(.*)', content)
        if not source_match:
            return {'error': 'No source URL found in article'}
        url = source_match.group(1).strip()
        auto_match = re.search(r'\*\*AutoGenerated:\*\*\s+(True|False)', content)
        auto_generated = auto_match.group(1) == 'True' if auto_match else False

    with _queue_lock():
        q_list = _read_queue()
        q_list.append({
            'id': str(uuid.uuid4()),
            'url': url,
            'status': 'pending',
            'auto_generated': auto_generated,
            'added_at': datetime.now().isoformat(),
        })
        _write_queue(q_list)
    return {'success': True}


def get_queue() -> list[dict]:
    return _read_queue()


def retry_queue_item(item_id: str) -> bool:
    with _queue_lock():
        q_list = _read_queue()
        item = next((i for i in q_list if i['id'] == item_id), None)
        if not item:
            return False

        item['status'] = 'pending'
        item['retry_count'] = 0
        item.pop('next_attempt_at', None)
        item.pop('last_error', None)
        item.pop('finished_at', None)

        _write_queue(q_list)
    return True


@contextlib.contextmanager
def _queue_lock():
    """Advisory lock guarding queue.json's read-modify-write cycle. fcntl.flock is
    stdlib and works across processes on the same host (not just threads in this
    process) -- needed because homelab-intake's intake_daemon.py, a separate
    long-running process, also reads and writes this same file (see
    homelab-intake/TODO.md -- that side still needs the matching lock)."""
    with open(QUEUE_LOCK_FILE, 'w') as lock_f:
        fcntl.flock(lock_f, fcntl.LOCK_EX)
        try:
            yield
        finally:
            fcntl.flock(lock_f, fcntl.LOCK_UN)


def _read_queue() -> list[dict]:
    if not os.path.exists(QUEUE_FILE):
        return []
    try:
        with open(QUEUE_FILE, 'r') as f:
            return json.load(f)
    except Exception:
        return []


def _write_queue(q_list: list[dict]) -> None:
    d = os.path.dirname(QUEUE_FILE)
    fd, tmp_path = tempfile.mkstemp(dir=d, prefix='.tmp-queue-', suffix='.json')
    try:
        with os.fdopen(fd, 'w') as f:
            json.dump(q_list, f, indent=2)
        os.replace(tmp_path, QUEUE_FILE)
    except Exception:
        if os.path.exists(tmp_path):
            os.remove(tmp_path)
        raise


def _cosine_similarity(a: list[float], b: list[float]) -> float:
    dot = sum(x * y for x, y in zip(a, b))
    norm_a = math.sqrt(sum(x * x for x in a))
    norm_b = math.sqrt(sum(y * y for y in b))
    if norm_a == 0 or norm_b == 0:
        return 0.0
    return dot / (norm_a * norm_b)


def _retrieve_similar_articles(question: str, top_k: int = 5) -> list[dict]:
    """Shared retrieval step behind search_articles() and search_articles_with_citations()
    -- reuses homelab-intake's existing embeddings index (index/articles.db) and
    nomic-embed-text model, mirroring homelab-intake/ask.py rather than importing it,
    same as the rest of this module reads homelab-intake's files directly by path
    instead of cross-repo importing."""
    if not os.path.exists(INDEX_DB):
        return []

    intake_env = dotenv_values(INTAKE_ENV_FILE)
    ollama_url = intake_env.get('OLLAMA_URL', 'http://127.0.0.1:11434')
    with open(INTAKE_CONFIG_FILE, 'r') as f:
        embedding_model = yaml.safe_load(f)['models']['embedding_model']

    resp = requests.post(
        f"{ollama_url}/api/embeddings",
        json={"model": embedding_model, "prompt": question[:8000]},
        timeout=30,
    )
    resp.raise_for_status()
    q_vec = resp.json()["embedding"]

    conn = sqlite3.connect(INDEX_DB)
    rows = conn.execute(
        "SELECT source_url, embedding FROM articles WHERE embedding IS NOT NULL"
    ).fetchall()

    scored = [
        (_cosine_similarity(q_vec, json.loads(embedding_json)), source_url)
        for source_url, embedding_json in rows
    ]
    scored.sort(reverse=True, key=lambda pair: pair[0])

    results = []
    for sim, source_url in scored[:top_k]:
        row = conn.execute(
            "SELECT file_path, title, tags, why_it_matters FROM articles WHERE source_url = ?",
            (source_url,),
        ).fetchone()
        if not row:
            continue
        file_path, title, tags_json, why_it_matters = row
        with open(file_path, 'r', encoding='utf-8') as article_file:
            content = article_file.read()
        _, body = _parse_frontmatter(content)
        results.append({
            'file_path': file_path, 'title': title, 'tags': tags_json,
            'why_it_matters': why_it_matters, 'source_url': source_url,
            'similarity': sim, 'body': body or '',
        })
    conn.close()
    return results


def search_articles(question: str, top_k: int = 5) -> str:
    """Semantic search over the archive -- plain-text result for the dashboard assistant."""
    if not os.path.exists(INDEX_DB):
        return "No article index found yet -- homelab-intake hasn't processed any articles."
    results = _retrieve_similar_articles(question, top_k)
    if not results:
        return "No matching articles found in the archive."
    blocks = [
        f"[{r['similarity']:.2f}] {r['title']}\nSource: {r['source_url']}\nTags: {r['tags']}\n"
        f"Why it matters: {r['why_it_matters']}\n\n{r['body'][:2000]}"
        for r in results
    ]
    return "\n\n---\n\n".join(blocks)


def search_articles_with_citations(question: str, top_k: int = 5) -> tuple[str, list[dict]]:
    """Same retrieval as search_articles(), but also returns citation records (article
    id + title) for AI Discuss's citation strips -- archive citations open the cited
    article in the reader rather than pointing at a file:line like repo citations do."""
    results = _retrieve_similar_articles(question, top_k)
    if not results:
        return "No matching articles found in the archive.", []
    blocks = []
    citations = []
    for r in results:
        blocks.append(f"[{r['similarity']:.2f}] {r['title']}\n\n{r['body'][:1500]}")
        citations.append({'article_id': os.path.basename(r['file_path']), 'title': r['title'], 'kind': 'archive'})
    return "\n\n---\n\n".join(blocks), citations
